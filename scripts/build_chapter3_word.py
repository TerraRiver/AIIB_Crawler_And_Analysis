def add_figure_ch3(doc: Document, img_path: Path, caption: str, width_cm: float = 15.6) -> None:
    """Embed a high-resolution PNG figure centered on the page with caption."""
    img_p = doc.add_paragraph()
    img_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    img_p.paragraph_format.space_before = Pt(8)
    img_p.paragraph_format.space_after = Pt(2)
    run = img_p.add_run()
    run.add_picture(str(img_path), width=Cm(width_cm))

    cap_p = doc.add_paragraph()
    cap_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap_p.paragraph_format.space_before = Pt(2)
    cap_p.paragraph_format.space_after = Pt(8)
    cap_run = cap_p.add_run(caption)
    cap_run.bold = True
    cap_run.font.name = "Times New Roman"
    cap_run.font.size = Pt(10.0)
    cap_run.font.color.rgb = RGBColor(0x1E, 0x29, 0x3B)
    cap_run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")


